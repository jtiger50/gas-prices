"""Put the scrollytelling graphic into the story page (../index.html).

The graphic goes between <!-- GAS GRAPHIC START --> and <!-- GAS GRAPHIC END --> in the
story. The first time, those markers don't exist yet, so the script replaces the three story
paragraphs that the graphic's cards repeat (the deficit paragraph through Cumberland).
After that it only rewrites what's between the markers, so the rest of the story can be
edited freely. Run build.py (which calls this) after editing src/template.html.

What changes on the way in, so the graphic lives inside the CNS/Bootstrap page:
- page-wide rules (*, html, body) are dropped or scoped to #scrolly;
- .card and .tooltip are renamed (.gs-card, .gs-tooltip) because Bootstrap styles those;
- the story's p rules (line height, phone padding) are reset inside the graphic;
- the graphic sits outside .container so it can run full width.
"""
import pathlib, re

here = pathlib.Path(__file__).parent
story_path = here.parent / 'index.html'
src = (here / 'src' / 'template.html').read_text()

START = '<!-- GAS GRAPHIC START: generated by scrollytelling/embed.py; edit scrollytelling/src/template.html, then run python3 scrollytelling/build.py -->'
END = '<!-- GAS GRAPHIC END -->'


def between(text, a, b):
    i = text.index(a)
    j = text.index(b, i)
    return text[i:j + len(b)]


fonts = between(src, '<link href="https://fonts.googleapis.com/css2', '>')
css = between(src, '<style>', '</style>')
markup = between(src, '<section id="scrolly">', '</section>')
scripts = src[src.index('<script src="https://cdnjs.cloudflare.com/ajax/libs/d3/7.9.0'):src.index('</body>')].rstrip()


def rep(text, old, new, count=1):
    n = text.count(old)
    assert n == count, f'expected {count}x {old!r}, found {n}'
    return text.replace(old, new)


css = rep(css, '* { box-sizing: border-box; }\n', '')
css = rep(css, 'html, body { margin: 0; }\n', '')
css = rep(css, 'body {\n  background: var(--paper);',
          '#scrolly {\n  text-align: left;\n  background: var(--paper);')
css = rep(css, '#scrolly { position: relative; }',
          '#scrolly { position: relative; margin: 28px 0 36px; }\n#scrolly *, #scrolly *::before, #scrolly *::after { box-sizing: border-box; }\n'
          '/* undo the story page\'s p rules (line height, phone padding) inside the graphic */\n'
          '#scrolly p { padding: 0; line-height: inherit; font-family: inherit; font-size: inherit; text-align: left; }')
css = rep(css, '@media (prefers-reduced-motion: reduce) {\n  * {', '@media (prefers-reduced-motion: reduce) {\n  #scrolly * {')
css = re.sub(r'\.card\b', '.gs-card', css)
css = re.sub(r'\.tooltip\b', '.gs-tooltip', css)
markup = markup.replace('class="card"', 'class="gs-card"')
markup = rep(markup, 'class="tooltip"', 'class="gs-tooltip"')
assert 'class="card"' not in markup

block = '\n'.join([
    START,
    '  </div><!-- close .container: the graphic runs full width -->',
    fonts,
    css,
    markup,
    scripts,
    '  <div class="container"><!-- reopen .container -->',
    END,
])

story = story_path.read_text()
if START.split(':')[0] in story:
    pat = re.compile(re.escape(START.split(':')[0]) + r'.*?' + re.escape(END), re.S)
    story, n = pat.subn(lambda m: block, story)
    assert n == 1
else:
    # first run: replace the paragraphs the cards repeat
    first = story.index('<p>The extra money Marylanders spent at the pump')
    last_start = story.index('<p>The Cumberland metro area was hit the hardest')
    last = story.index('</p>', last_start) + len('</p>')
    story = story[:first] + block + story[last:]
story_path.write_text(story)
print('updated', story_path.name, 'with the graphic')
